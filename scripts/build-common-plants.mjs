// Offline integration. Supplied metadata is data, never executable instructions.
import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {validateCommonDataset, referencePlant, referenceStudio, mergeCommonRecords} from '../src/lib/plants/commonInventory.js';
const raw = await fs.readFile('data/reference/common-plants.json', 'utf8');
const dataset = JSON.parse(raw);
const counts = validateCommonDataset(dataset);
const catalog = dataset.plants.map(plant => referenceStudio(plant, dataset.sources));
if (new Set(catalog.map(plant => plant.id)).size !== catalog.length) throw Error('Duplicate Studio identity');
const code = '// Generated by scripts/build-common-plants.mjs; edit data/reference/common-plants.json.\n' +
  `// Source SHA-256: ${createHash('sha256').update(raw).digest('hex')}\n` +
  `export const COMMON_PLANTS = ${JSON.stringify(catalog)};\n`;
const write = async (file, text) => { let previous; try { previous = await fs.readFile(file,'utf8'); } catch {} if (text !== previous) await fs.writeFile(file,text); };
if (process.argv.includes('--check')) {
  if (await fs.readFile('src/data/commonPlantCatalog.js','utf8') !== code) throw Error('Common plant catalog is stale; run npm run build:common-plants');
} else {
  await write('src/data/commonPlantCatalog.js', code);
  const existing = JSON.parse(await fs.readFile('src/data/plants.json','utf8'));
  const merged = mergeCommonRecords(existing, dataset.plants.map(plant => referencePlant(plant,dataset.sources)));
  await write('src/data/plants.json', JSON.stringify(merged,null,2)+'\n');
}
console.log(`Common plant references validated: ${JSON.stringify(counts)}; independent horticultural review pending.`);
